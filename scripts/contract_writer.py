"""Shared writer for the ZTIE contract generators (Story C.3, RD-034).

Every ``gen_<name>_contract.py`` used to carry its OWN identical ``main()`` loop:
open each output path, ``json.dump(SCHEMA, fh, indent=2)``, write a trailing
newline, ``print`` the path. That loop was copy-pasted 10 times — a real
copy-drift surface (a fix to the serialization in one generator would silently
miss the other nine). C.3 collapses that duplicated *writer* into this one
module while leaving each contract's ``SCHEMA`` (the genuine per-contract data)
exactly where it is, byte-for-byte unchanged.

Design invariants (MUST match the pre-C.3 per-generator behaviour exactly, or the
regenerated schemas drift):
  * serialization is ``json.dump(schema, fh, indent=2)`` then ``fh.write("\\n")``
    — no ``sort_keys``, no custom ``separators`` (default ``", "`` / ``": "``),
    a single trailing newline. This is what all 10 generators did.
  * ``open(path, "w", encoding="utf-8")``.
  * ``os.makedirs(os.path.dirname(path), exist_ok=True)`` before writing. The
    older generators (reject/routing/classification) omitted this, but their
    target dirs (``schemas/`` + ``lambdas/hub_ingest/``) always already exist, so
    adding a no-op ``makedirs`` produces byte-identical FILES; it only removes a
    latent "dir missing" failure mode. The regenerated bytes are unchanged
    (proven by the C.3 golden-hash no-drift check).
  * ``print(f"wrote {path}")`` per path, preserving the operator-visible output.

Stdlib only (no PyPI) so it runs in the INTEGRATIONS_ONLY build sandbox.
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterable
from typing import Any


def repo_root() -> str:
    """Absolute repo root (the parent of ``scripts/``).

    Mirrors the ``os.path.dirname(os.path.dirname(os.path.abspath(__file__)))``
    each generator computed for its ``repo`` local, but anchored on THIS file so
    every contract resolves output paths identically regardless of caller.
    """

    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def resolve_out_paths(rel_paths: Iterable[Iterable[str]]) -> list[str]:
    """Turn repo-root-relative path segment tuples into absolute output paths.

    Each entry is a tuple of path segments, e.g.
    ``("schemas", "reject.contract.v1.json")`` or
    ``("lambdas", "hub_ingest", "reject.contract.v1.json")`` — exactly the
    segments the per-generator ``os.path.join(repo, ...)`` calls used.
    """

    root = repo_root()
    return [os.path.join(root, *segments) for segments in rel_paths]


def write_contract(schema: dict[str, Any], out_paths: Iterable[str]) -> None:
    """Write ``schema`` to every path in ``out_paths`` (byte-identical to pre-C.3).

    This is the single, shared replacement for the 10 duplicated ``main()`` loops.
    """

    for out_path in out_paths:
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as fh:
            json.dump(schema, fh, indent=2)
            fh.write("\n")
        print(f"wrote {out_path}")
